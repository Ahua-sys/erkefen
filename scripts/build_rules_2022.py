def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()

    # 幂等：剔除旧 -2022- 行
    kept, dropped = [], 0
    with open(L.RULES_JSONL, encoding="utf-8") as f:
        for line in f:
            s = line.strip()
            if not s:
                continue
            if json.loads(s).get("policy_id") == POLICY:
                dropped += 1
                continue
            kept.append(s)
    new_lines = [json.dumps(r, ensure_ascii=False) for r in rules]
    if a.dry_run:
        print(f"将剔除旧 {POLICY} 行 {dropped} 条，写入 {len(rules)} 条新规则")
        ids = [r["rule_id"] for r in rules]
        assert len(ids) == len(set(ids)), "rule_id 重复"
        print("rule_id 唯一性 OK；示例:", ids[:3], "...", ids[-3:])
        return
    with open(L.RULES_JSONL, "w", encoding="utf-8") as f:
        for s in kept:
            f.write(s + "\n")
        for s in new_lines:
            f.write(s + "\n")
    print(f"已重写 rules.jsonl：保留 {len(kept)} 条 + 新增 {len(rules)} 条（剔除旧 {dropped} 条）")


if __name__ == "__main__":
    main()
